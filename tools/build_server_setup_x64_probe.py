def put(path,value):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True,mode=0o700)
    raw=(json.dumps(value,sort_keys=True,indent=2)+'\n').encode()
    with path.open('xb') as stream:stream.write(raw);stream.flush();os.fsync(stream.fileno())


def fresh(path):
    path=Path(os.path.abspath(path));archives.directory(path.parent,create=True)
    require(not os.path.lexists(path),'x64-setup-existing-output-preserved')
    path.mkdir(mode=0o700);return path


def copy(source,target):
    expected=files.identity(source);target.parent.mkdir(parents=True,exist_ok=True,mode=0o700)
    with files.plain_file(source) as incoming,target.open('xb') as outgoing:
        require(archives.hash_stream(incoming,expected['bytes'],outgoing)==expected['sha256'],'x64-setup-copy-changed')
    target.chmod(0o444);return expected


