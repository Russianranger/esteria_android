        isolated.run_owned([cmake,'--build',output/'build','--parallel','2','--target',*TARGETS],
            output/'diagnostics/build.log',environment,cwd=ROOT,timeout=10800)
        candidates={'dbimport':[output/'build/bin/dbimport',output/'build/src/tools/dbimport'],
            'playerbots-schema':[output/'build/esteria_playerbots_database_reference']}
        payload=output/'payload';payload.mkdir();executables=[];built={}
        for name,paths in candidates.items():
            found=[p for p in paths if p.is_file()]
            require(len(found)==1,'x64-setup-output-executable-set');path=found[0]
            original=copy(path,payload/'originals'/name)
            executable=payload/'bin'/name;copy(path,executable);executable.chmod(0o755)
            debug=payload/'debug'/(name+'.debug');debug.parent.mkdir(exist_ok=True)
            files.bounded_command(['objcopy','--only-keep-debug',str(path),str(debug)],timeout=120)
            files.bounded_command(['strip','--strip-debug',str(executable)],timeout=120)
            files.bounded_command(['objcopy','--add-gnu-debuglink='+str(debug),str(executable)],timeout=120)
            require(name+'.debug' in files.bounded_command(['readelf','--string-dump=.gnu_debuglink',str(executable)]),
                    'x64-setup-paired-debug-link-missing')
